import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const origin = process.env.TEST_BASE_URL || 'http://localhost:3000'
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${origin}/contact?ref=a%20b#address`)
  await page.waitForLoadState('networkidle')
  assert.equal(await page.locator('html').getAttribute('lang'), 'en')
  await page.evaluate(() => document.fonts.ready)
  assert.match(await page.locator('h1').evaluate(element => getComputedStyle(element).fontFamily), /Zalando/)
  assert.match(await page.locator('body').evaluate(element => getComputedStyle(element).fontFamily), /Space Mono|Space_Mono/)
  const selector = page.getByRole('button', { name: 'Choose language: English' })
  assert.equal(await selector.getAttribute('aria-expanded'), 'false')
  await selector.focus()
  await page.keyboard.press('Space')
  assert.equal(await selector.getAttribute('aria-expanded'), 'true')
  await page.keyboard.press('Escape')
  assert.equal(await selector.getAttribute('aria-expanded'), 'false')
  assert.equal(await selector.evaluate(element => element === document.activeElement), true)
  await selector.click()
  assert.equal(await page.getByRole('link', { name: 'Switch language to English' }).getAttribute('aria-current'), 'true')
  await page.locator('h1').click()
  assert.equal(await selector.getAttribute('aria-expanded'), 'false')
  await selector.click()
  const desktopSwitch = page.getByRole('link', { name: 'Αλλαγή γλώσσας σε Ελληνικά' }).first()
  assert.equal(await desktopSwitch.getAttribute('href'), '/el/contact?ref=a%20b#address')
  await desktopSwitch.click()
  await page.waitForLoadState('networkidle')
  assert.equal(new URL(page.url()).pathname, '/el/contact')
  assert.equal(new URL(page.url()).hash, '#address')
  assert.equal(await page.locator('html').getAttribute('lang'), 'el')
  assert.equal(await page.title(), 'Επικοινωνία με τη Meister')
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://meister-storefront.vercel.app/el/contact')
  assert.equal(await page.locator('link[hreflang="en"]').getAttribute('href'), 'https://meister-storefront.vercel.app/contact')
  assert.equal(await page.evaluate(() => localStorage.getItem('meister_locale')), 'el')
  const typography = await page.locator('h1').evaluate(element => ({ family: getComputedStyle(element).fontFamily, weight: getComputedStyle(element).fontWeight }))
  assert.match(typography.family, /Syne/)
  assert.match(await page.locator('body').evaluate(element => getComputedStyle(element).fontFamily), /Cascadia/)
  assert.equal(typography.weight, '700')
  // A regular Next Link navigation must retain the Greek provider and URL.
  await Promise.all([page.waitForURL('**/el/fins'), page.getByRole('link', { name: 'ΠΕΔΙΛΑ', exact: true }).first().click()])
  await page.waitForLoadState('networkidle')
  assert.equal(new URL(page.url()).pathname, '/el/fins')
  assert.equal(await page.locator('html').getAttribute('lang'), 'el')
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 850 })
    await page.goto(`${origin}/el/contact?ref=mobile#address`)
    await page.getByRole('button', { name: 'Άνοιγμα μενού', exact: true }).click()
    const mobileSelector = page.locator('#mobile-menu').getByRole('button', { name: 'Επιλογή γλώσσας: Ελληνικά' })
    await mobileSelector.click()
    const panel = page.locator('[id="' + await mobileSelector.getAttribute('aria-controls') + '"]')
    const bounds = await panel.boundingBox()
    assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= width, 'Language choices fit the mobile viewport')
    const mobileSwitch = page.locator('#mobile-menu').getByRole('link', { name: 'Switch language to English' })
    assert.equal(await mobileSwitch.getAttribute('href'), '/contact?ref=mobile#address')
    await mobileSwitch.click()
    await page.waitForLoadState('networkidle')
    assert.equal(await page.locator('html').getAttribute('lang'), 'en')
  }
  const account = await page.request.get(`${origin}/el/account?tab=orders`, { maxRedirects: 0 })
  assert.equal(account.status(), 307)
  const signIn = new URL(account.headers().location, origin)
  assert.equal(signIn.pathname, '/el/sign-in')
  assert.equal(signIn.searchParams.get('redirect_url'), '/el/account?tab=orders')
  for (const path of ['/el/api/cart', '/el/docs', '/el/_next/image']) assert.equal((await page.request.get(`${origin}${path}`)).status(), 404)
  const html = await page.request.get(`${origin}/contact`, { headers: { 'x-meister-locale': 'el', 'x-meister-original-path': '/el/contact' } })
  assert.match(await html.text(), /<html[^>]+lang="en"/)
  await page.goto(`${origin}/docs`)
  assert.equal(await page.locator('html').getAttribute('lang'), 'en')
  assert.equal(await page.locator('link[hreflang="el"]').count(), 0)
  await page.goto(`${origin}/el/products/carbon-blade-fins`)
  const canonical = await page.locator('link[rel="canonical"]').getAttribute('href')
  const breadcrumbs = await page.locator('script[type="application/ld+json"]').evaluateAll(elements => elements.map(element => JSON.parse(element.textContent)).flat().find(schema => schema['@type'] === 'BreadcrumbList'))
  assert.equal(breadcrumbs.itemListElement.at(-1).item, canonical)
  assert.equal(breadcrumbs.itemListElement[1].item, 'https://meister-storefront.vercel.app/el/fins')
  assert.deepEqual(errors, [])
  console.log('Locale browser checks passed: English/Greek SSR, switch/query/hash, client navigation, 320/390/768/1440, account and reserved paths, Greek font.')
} finally { await browser.close() }
